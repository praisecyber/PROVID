import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(`dist/${name}`, root), 'utf8');
let html = await read('index.html');
html = html.replace('<link rel="stylesheet" href="style.css">', `<style>${await read('style.css')}</style>`);
for (const name of ['studio.js', 'media-brief.js']) {
  const source = await read(name);
  html = html.replace(`<script type="module" src="${name}"></script>`, `<script>(async () => {\n${source}\n})().catch(error => { const notice = document.getElementById('notice'); if (notice) notice.textContent = 'Unable to open workspace: ' + error.message; });</script>`);
}
await mkdir(new URL('generated/', root), { recursive: true });
await writeFile(new URL('generated/studio.js', root), `// Generated by scripts/bundle-studio.mjs.\nexport default ${JSON.stringify(html)};\n`);
console.log('Bundled PROVID studio for Expo native and web.');
